const BY_SLUG = new Map(LEGAL_DOCUMENTS.map((item) => [item.slug, item]));

export function getLegalDocument(slug: string) {
  return BY_SLUG.get(slug) ?? null;
}

export type LegalSurface = "hidden" | "index" | "document" | "missing";

/** Flag off hides every legal route. An unknown slug stays missing. */
export function legalSurface(enabled: boolean, slug?: string | null): LegalSurface {
  if (!enabled) {
    return "hidden";
  }
  if (!slug) {
    return "index";
  }
  return getLegalDocument(slug) ? "document" : "missing";
}
